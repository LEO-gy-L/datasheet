# -*- coding: utf-8 -*-
"""
自定义异常
==========
为什么不直接用 Exception / ValueError，而要多写几个类：

    因为**接口层需要按错误类型返回不同的 HTTP 状态码**。
    如果全用 ValueError，接口里就只能写 `except ValueError` 一把抓，
    想区分"用户输入错了"和"上游模型挂了"就只剩"去匹配异常信息里的字符串"这条路 ——
    改一个字就失灵。

    自定义类型让这件事变成一眼可读：

        EmptyQuestionError    -> 400  用户输入有问题，改了再来
        IndexNotFoundError    -> 500  服务端自己没准备好（向量库没建）
        ModelCallError        -> 503  上游大模型挂了/限流，过会儿重试可能就好

    另外，它们都继承同一个 RAGError，所以"捕获本项目全部业务错误"可以只写一句
    `except RAGError`。

⚠️ 命名约定：类名以 Error 结尾、继承 Exception。
   不要写成 XxxException —— 项目里统一一种叫法，grep 的时候不会漏。
"""
from __future__ import annotations


class RAGError(Exception):
    """本项目所有业务异常的基类。

    自己写 except 时优先捕获它，而不是裸的 Exception ——
    裸 Exception 会把 Ctrl+C、内存不足、语法错误之类也一起吞掉，调试会很难受。
    """


class EmptyQuestionError(RAGError):
    """问题为空，或者全是空白字符。"""


class IndexNotFoundError(RAGError):
    """向量库不存在：还没有建库（没跑 indexer），或者 vectorstore/ 被删了。"""


class ModelCallError(RAGError):
    """调用大模型失败：网络抖动、余额不足、被限流。

    单独一类的原因：这是**唯一值得重试**的错误。
    """


# ---------------------------------------------------------------------------
# 下面是 2026-10-03 接入数据库后新增的**通用业务异常**。
#
# 基类仍是 RAGError（名字里带 RAG 只是历史原因，它就是"本项目业务异常"的意思），
# 这样接口层只写一句 `except RAGError` 就能兜住所有业务错误。
#
# 每类对应一个 HTTP 状态码，映射规则写在各自文档串里。
# 划分依据是"调用方看到之后该怎么办"，不是"服务端哪里出错了"：
# ---------------------------------------------------------------------------


class AuthError(RAGError):
    """登录失败：账号不存在，或密码不对。

    -> 401。刻意**不区分**是账号错还是密码错 ——
    区分了等于告诉攻击者"这个账号存在，继续猜密码吧"。
    """


class AccountDisabledError(RAGError):
    """账号被管理员禁用。

    -> 403。为什么不做成 401：凭证本身是有效的（他就是这个人），
    只是不允许进入。前端收到 403 应该提示"账号已禁用"而不是踢回登录页 ——
    踢回去他会反复登录、反复被拒，以为是系统坏了。
    """


class ForbiddenError(RAGError):
    """已登录，但没有权限做这件事（比如普通用户想改别人的账号）。

    -> 403。
    """


class NotFoundError(RAGError):
    """要操作的东西不存在（历史记录 id、用户 id、反馈 id 找不到）。

    -> 404。另一层意思：**不该被看到的资源也用 404 而不是 403** ——
    用 403 会说漏嘴"这个东西存在，只是不给你看"。
    """


class ConflictError(RAGError):
    """冲突：想创建的账号已经存在、想改的账号名被别人占了。

    -> 409。为什么不用 400：这不是"参数格式错"，而是"参数没问题，
    但和当前数据状态撞了"，前端提示语也不同（"该账号名已被占用"）。
    """

