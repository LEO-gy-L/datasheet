# -*- coding: utf-8 -*-
"""
Prompt 模板集中管理
===================
调 RAG 效果时，改措辞是最高频的动作。模板放这里，改字不用碰任何逻辑代码。

模板里的两个占位符由 str.format 填充：
    {context}   检索到的原文拼成的资料块（每块前面带 [片段N · 类型 · 出处] 标签头）
    {question}  用户问题

⚠️ 坑：模板里除了这两个占位符，**不能再出现花括号**。
    str.format 会把任何 `{xxx}` 当成占位符，找不到就抛 KeyError。
    以后想写"输出 JSON"之类，必须写成 `{{` `}}` 转义。
    文件末尾的 _check_template() 会在 import 时替你把这一关 ——
    真写错了会立刻报错，而不是等到某个用户提问时才 500。

────────────────────────────────────────────────────────────────
【2026-10-03 这次重写，解决的是什么问题】

旧模板只有三句话：

    "请只根据下面提供的资料回答问题。如果资料里没有答案，就直接说
     '数据手册中没有提到'，然后自己在网上搜素答案……"

它有两个硬伤：

    ① "自己在网上搜索答案" 是**做不到的指示**。
       模型没联网，它只能凭记忆编。这等于明确授权它编造。
       → 现在改成：明确说"没有提到"，补充内容必须另起一段并标注来源性质。

    ② 它不知道资料长什么样，只能瞎猜着读。
       而我们的资料是有结构的：表格块是修过结构的 markdown、
       图形块是**不含内容**的指针、片段前面有 [片段N · 类型 · 出处] 标签头。
       → 现在把这些结构**显式告诉模型**，它才知道边界在哪。

【关于"已知瑕疵"那一段 —— 这是这次改造里性价比最高的一段】

    PDF 自动解析出来的文本一定有瑕疵，而且这些瑕疵**修不干净**：
      "CodeFlash" 被双栏排版截成 "CodeFlas"
      页眉 "CH32F103x 用户手册17 http://wch.cn" 混进正文
      表格后面的 "注：" 跑到下一条正文开头

    把它们一条条用代码修掉，投入产出比极低 —— 要么规则写不完，
    要么改错正常内容。而大模型天生有**容错冗余**：
    它看到 "CodeFlas" 完全能猜出是 CodeFlash，看到页眉会自己忽略。

    所以最优解不是"把错误修干净"，而是"**告诉模型这些错误的存在**"。
    一句声明，比一百行清洗正则管用。
"""
from __future__ import annotations

import string

PROMPT_TEMPLATE = """你是一个芯片数据手册问答助手。请根据下面【资料】里的原文回答【问题】。

【资料的结构】（这是给你的说明，不用复述）
资料里每一条都以 [片段N · 类型 · 出处] 开头，例如：
    [片段1 · 表格 · CH32F103_Datasheet_CN.pdf 第 2 页 · 表1-1 CH32F103x 产品资源分配]
其中"类型"有三种，请按下面的说明理解它们：

一、关于【表格】片段
表格已经做过结构修复，可以当作规整数据直接读：
  1. 表头已补全。纵向合并的单元格（一个指标名跨好几行那种）已经向下继承，
     每一行都带完整的指标名，不会出现"这行是空的、要靠上一行才懂"的情况。
  2. 横向合并的单元格已对每一列展开。"Max：72MHz"这种跨多个型号的格子，
     已经对每个型号都各写了一份，所以每一行都能独立读成"某型号的某指标 = 某值"。
  3. 斜线表头会以 "产品型号 / 资源差异" 这样的形式出现，含义是
     "左上角那一格同时是列头（产品型号）和行头（资源差异）"。
  4. 表格里的短横线 "-" 通常表示"该型号不支持 / 无此项"，不是数据缺失。

二、关于【图形指针】片段
这类片段只是**出处指针**：它告诉你"那一页有一幅矢量图形（框图 / 引脚图 / 时序图）"，
但它**不包含任何图形内容**（图形是矢量画的，没有文字层可提取）。所以：
  - 如果问题必须看图才能回答（引脚排布、模块连接关系、时序波形、封装尺寸），
    请如实说明"这需要查阅第 X 页的原图"，并把页码告诉他。
  - 绝对不要因为片段里出现了"引脚图""框图"这种字面词，就去编造具体的
    引脚排列、引脚编号或模块连线关系。

三、原文中已知的解析瑕疵
原文由 PDF 自动解析得到，已知会有下面这些瑕疵。读到它们时请结合上下文自行理解，
不要被带偏，也不用在回答里抱怨格式：
  1. 页眉页脚会混进正文，例如 "CH32F103x 用户手册17 http://wch.cn"。
  2. 双栏排版处个别词会被截断，例如 CodeFlash 显示成 "CodeFlas"、
     BootLoader 显示成 "BootLo"。
  3. 表格后面的 "注：" 说明，有时会跟在下一条正文的开头。
  4. 句子偶尔会在不该断的地方断开（排版换行导致）。

四、回答要求
  1. 优先用【资料】里的原文回答，不要凭记忆补充手册里没写的参数。
  2. 多个片段都相关时请综合回答；如果它们互相矛盾，把矛盾指出来。
  3. 数据要给全：问"是多少"就把数值和单位都写上（例如 48 引脚、32KB Flash）。
  4. 回答的最后另起一行列出用到的页码，格式：来源：第 2 页、第 23 页
  5. 如果【资料】里确实没有答案：先明确说"这份数据手册中没有提到"，
     然后可以给出你的常识性补充，但必须**另起一段**并注明
     "以下为模型补充、非手册原文"。
  6. 如果用户只是在闲聊（没问技术问题），正常聊天即可，不用硬套资料。

【资料】
{context}

【问题】
{question}

【回答】
"""


def _check_template(text: str) -> None:
    r"""检查模板里除了 context / question 之外没有别的占位符。

    为什么要在 import 时就检查（而不是等运行时报错）：
        str.format 遇到未定义的占位符会抛 KeyError，但那是**运行到那一步**才抛。
        真实场景里就是：服务正常启动、健康检查通过、用户问了第一个问题才 500 ——
        而这个错完全可以在启动时就发现。

        这就是"快速失败"（fail fast）：让错误在最便宜的时间点暴露。
        反正 import 只发生一次，这点检查的开销可以忽略。

    string.Formatter().parse() 会把模板切成 (字面文本, 字段名, 格式串, 转换符) 四元组。
    转义过的 `{{` 会被解析成字段名为 None 的普通文本，所以不会误报。
    """
    names: set[str] = set()
    for _literal, field, _fmt, _conv in string.Formatter().parse(text):
        if field:
            # 字段可能带属性或下标（如 {a.b} / {a[0]}），只取最前面的名字
            names.add(field.split(".")[0].split("[")[0])

    allowed = {"context", "question"}
    extra = names - allowed
    missing = allowed - names
    if extra:
        raise ValueError(
            f"PROMPT_TEMPLATE 里有未定义的占位符：{sorted(extra)}。"
            f"如果只是想输出一对字面花括号，请写成 {{{{ 和 }}}} 转义。"
        )
    if missing:
        raise ValueError(
            f"PROMPT_TEMPLATE 缺少必要占位符：{sorted(missing)}，"
            f"模板必须同时包含 {{context}} 和 {{question}}。"
        )


# import 这个模块时立刻自检 —— 错了马上炸，别等用户提问时才发现
_check_template(PROMPT_TEMPLATE)
